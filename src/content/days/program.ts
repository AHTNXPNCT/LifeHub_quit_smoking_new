function phaseFor(day: number) {
  return phases.find((phase) => day >= phase.from && day <= phase.to) ?? { from: 366, to: Infinity, name: "Продолжение", category: "Дальнейшее развитие", intro: "Программа завершена, но ваш путь продолжается в свободном темпе." };
}

export function getProgramDay(day: number): DailyProgram {
  const safeDay = Math.max(1, Math.floor(day));
  const index = (safeDay - 1) % (topics.length * angles.length);
  const topic = topics[Math.floor(index / angles.length) % topics.length];
  const angle = angles[index % angles.length];
  const phase = phaseFor(safeDay);
  const technique = techniques[(safeDay * 3 + Math.floor(safeDay / 7)) % techniques.length];
  const fact = facts[(safeDay * 5 + Math.floor(safeDay / 11)) % facts.length];
  const source = sources[safeDay % sources.length];
  const xp = 20 + Math.min(30, Math.floor(safeDay / 30) * 2) + (safeDay % 5) * 2;
  return {
    day: safeDay,
    phase: phase.name,
    title: `${angle}: ${topic}`,
    category: phase.category,
    description: `${phase.intro} Фокус ${safeDay}-го дня — «${topic}»: рассмотрите его как наблюдение, а не экзамен.` ,
    fact: `${fact} Сегодня соотнесите это с темой «${topic}».`,
    source,
    exercise: `${angle} привычный сценарий «${topic}». Сделайте три спокойных выдоха, назовите импульс и запишите одно действие, которое поддержит ваш выбор сегодня.`,
    technique,
    mission: `${angle} один живой пример темы «${topic}» до конца дня и ответьте на него новым способом; отметьте, что изменилось.`,
    question: `Если сегодня я выбираю подход «${angle.toLowerCase()}» к теме «${topic}», что оказалось неожиданным и какой выбор я хочу повторить завтра?`,
    recommendation: `Сделайте полезный вариант заметным и доступным заранее — так на него потребуется меньше усилий в момент усталости.`,
    xp,
    completionCondition: "Прочитать материал, выполнить упражнение и сохранить короткий ответ.",
    test: safeDay % 7 === 0 ? {
      question: `Какой подход лучше поддержит навык «${topic}»?`,
      options: ["Ждать идеального настроения", "Заметить триггер и выбрать маленькое действие", "Ругать себя за каждую мысль"],
      answer: 1,
    } : undefined,
    natureDelta: 10,
  };
}

export const program365 = Array.from({ length: 365 }, (_, index) => getProgramDay(index + 1));
export const programPhases = phases;

export function verifyProgramUniqueness(days = program365) {
  const keys: (keyof DailyProgram)[] = ["title", "description", "fact", "exercise", "mission", "question"];
  return keys.map((key) => ({ key, unique: new Set(days.map((day) => String(day[key]).trim().toLowerCase())).size, total: days.length }));
}
